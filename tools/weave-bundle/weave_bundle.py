#!/usr/bin/env python3
"""Configure an independent Weave deployment and reuse its native operator bootstrap."""
import argparse
from contextlib import contextmanager
import fcntl
import ipaddress
import json
import os
from pathlib import Path
import re
import secrets
import subprocess
import sys
from urllib.parse import urlsplit

HERE = Path(__file__).resolve().parent
if not (HERE / 'configuration.py').exists():
    sys.path.insert(0, str(HERE.parent / 'server-bundle'))
from configuration import ConfigurationError, image_reference, normalize_origin, private_read, read_model_key, write_private

STATE = '.weave-state.local.json'
HEADER = '# Generated by Weave standalone deployment.\n'


def read_json(path):
    if path.stat().st_size > 65536:
        raise ConfigurationError('Selected configuration is too large.')
    def unique(pairs):
        result = {}
        for k, v in pairs:
            if k in result:
                raise ConfigurationError('Duplicate configuration field.')
            result[k] = v
        return result
    return json.loads(path.read_text(), object_pairs_hook=unique)


def validate_lock(value):
    if not isinstance(value, dict) or set(value) != {'version', 'bundleVersion', 'kind', 'components'} or value['version'] != 1 or value['kind'] != 'weave-standalone':
        raise ConfigurationError('Use the selected independent Weave image lock.')
    if set(value['components']) != {'weave', 'postgres'}:
        raise ConfigurationError('The standalone lock must contain only Weave and PostgreSQL.')
    for item in value['components'].values():
        image_reference(item['image'])
    if value['components']['postgres'].get('major') != 16 or not re.fullmatch(r'[0-9a-f]{40}', value['components']['weave'].get('sourceRevision', '')):
        raise ConfigurationError('The lock needs PostgreSQL 16 and an exact Weave source.')
    return value


class Deployment:
    def __init__(self, directory=HERE, runner=subprocess.run):
        self.root = Path(directory).resolve()
        self.runner = runner

    @contextmanager
    def lock(self):
        p = self.root / (STATE + '.lock')
        fd = os.open(p, os.O_CREAT | os.O_RDWR | getattr(os, 'O_NOFOLLOW', 0), 0o600)
        try:
            if os.fstat(fd).st_uid != os.geteuid() or os.fstat(fd).st_mode & 0o077:
                raise ConfigurationError('The deployment lock must be private and owned by this operator.')
            fcntl.flock(fd, fcntl.LOCK_EX)
            yield
        finally:
            os.close(fd)

    def load(self):
        state = json.loads(private_read(self.root / STATE, 65536))
        if state.get('version') != 1:
            raise ConfigurationError('Unsupported standalone state.')
        validate_lock(state['images'])
        if any(not isinstance(state['secrets'].get(k), str) or not re.fullmatch(r'[0-9a-f]{64}', state['secrets'][k]) for k in ('db', 'jwt', 'vault', 'bootstrap')):
            raise ConfigurationError('Stored encryption and database keys are invalid; no key was regenerated.')
        if type(state.get('bootstrapPending')) is not bool or not isinstance(state.get('apiKey'), str):
            raise ConfigurationError('Invalid stored operator receipt.')
        return state

    def configure(self, path):
        path = Path(path).resolve()
        cfg = read_json(path)
        fields = {'origin', 'port', 'bindAddress', 'forgeOrigin', 'forgeWorkspaceId', 'model', 'modelKeyFile'}
        if not isinstance(cfg, dict) or set(cfg) - fields:
            raise ConfigurationError('Use only the documented standalone settings.')
        cfg['origin'] = normalize_origin(cfg.get('origin'))
        port = cfg.setdefault('port', 8081)
        if type(port) is not int or not 1 <= port <= 65535:
            raise ConfigurationError('Select a valid port.')
        cfg['bindAddress'] = str(ipaddress.IPv4Address(cfg.get('bindAddress', '0.0.0.0')))
        public_port = urlsplit(cfg['origin']).port or (443 if cfg['origin'].startswith('https:') else 80)
        if cfg['origin'].startswith('http:') and public_port != port:
            raise ConfigurationError('Direct HTTP origin must match the published port.')
        cfg['forgeOrigin'] = normalize_origin(cfg['forgeOrigin']) if cfg.get('forgeOrigin') else ''
        workspace = cfg.setdefault('forgeWorkspaceId', '')
        if not isinstance(workspace, str) or (workspace and not re.fullmatch(r'[A-Za-z0-9_-]{1,128}', workspace)) or bool(workspace) != bool(cfg['forgeOrigin']):
            raise ConfigurationError('Forge integration needs its existing native organization ID and origin together.')
        cfg.setdefault('model', 'deepseek-flash')
        if not isinstance(cfg['model'], str) or not re.fullmatch(r'[A-Za-z0-9_./:-]{1,128}', cfg['model']):
            raise ConfigurationError('Provide a valid model identifier.')
        key_path = cfg.pop('modelKeyFile', '')
        if not isinstance(key_path, str):
            raise ConfigurationError('modelKeyFile must be a private file path.')
        model_key = read_model_key(path.parent / key_path) if key_path else ''
        images = validate_lock(read_json(self.root / 'images.lock.json'))
        with self.lock():
            p = self.root / STATE
            if p.exists():
                state = self.load()
                if state['settings'] != cfg or state['images'] != images or state['modelKey'] != model_key:
                    raise ConfigurationError('Existing deployment differs; its identity, keys and volumes were preserved.')
            else:
                if (self.root / '.env').exists() or (self.root / '.env').is_symlink() or (self.root / 'operator-key.local').exists():
                    raise ConfigurationError('Existing private deployment files were preserved.')
                state = {'version': 1, 'settings': cfg, 'images': images, 'project': 'weave-standalone-' + secrets.token_hex(4),
                         'workspace': workspace or 'ops-' + secrets.token_hex(12), 'username': 'operator-' + secrets.token_hex(4),
                         'dbUser': 'wv_' + secrets.token_hex(4), 'modelKey': model_key, 'apiKey': '', 'bootstrapPending': False,
                         'secrets': {k: secrets.token_hex(32) for k in ('db', 'jwt', 'vault', 'bootstrap')}}
                write_private(p, state)
            self.export(state)
        return {'configuration': 'saved', 'servicesStarted': False}

    def export(self, state):
        s, c = state['secrets'], state['settings']
        env = {'WS_PROJECT': state['project'], 'WS_WEAVE_IMAGE': state['images']['components']['weave']['image'],
               'WS_POSTGRES_IMAGE': state['images']['components']['postgres']['image'], 'WS_DB_USER': state['dbUser'],
               'WS_DB_PASSWORD': s['db'], 'WS_DATABASE_URL': f"postgres://{state['dbUser']}:{s['db']}@db:5432/weave?sslmode=disable",
               'WS_JWT_SECRET': s['jwt'], 'WS_VAULT_KEY': s['vault'], 'WS_BOOTSTRAP_PASSWORD': s['bootstrap'],
               'WS_BIND_ADDRESS': c['bindAddress'], 'WS_PORT': str(c['port']), 'WS_FORGE_ORIGIN': c['forgeOrigin'],
               'WS_FORGE_SESSION_URL': c['forgeOrigin'] + '/api/v1/auth/get-session' if c['forgeOrigin'] else '',
               'WS_FORGE_WORKSPACE': c['forgeWorkspaceId'], 'WS_MODEL_KEY': state['modelKey'], 'WS_MODEL': c['model']}
        from tempfile import NamedTemporaryFile
        path = self.root / '.env'
        if path.exists() or path.is_symlink():
            if not private_read(path, 65536).startswith(HEADER):
                raise ConfigurationError('Unrelated .env was preserved.')
        with NamedTemporaryFile(mode='w', dir=self.root, delete=False) as f:
            tmp = Path(f.name)
            os.fchmod(f.fileno(), 0o600)
            f.write(HEADER + ''.join(k + '=' + json.dumps(v).replace('$', r'\$') + '\n' for k, v in sorted(env.items())))
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)

    def compose(self, arguments, payload=None):
        env = {k: v for k, v in os.environ.items() if not k.startswith(('WS_', 'COMPOSE_'))}
        result = self.runner(['docker', 'compose', '--project-directory', str(self.root), *arguments], env=env,
                             capture_output=True, text=True, input=payload, timeout=240)
        if result.returncode:
            raise ConfigurationError('Compose operation failed; no private logs or credentials were printed.')
        return result.stdout

    def bootstrap(self):
        with self.lock():
            state = self.load()
            if not state['apiKey']:
                if state['bootstrapPending']:
                    raise ConfigurationError('Bootstrap outcome is unresolved; restore the private receipt instead of recreating a key.')
                state['bootstrapPending'] = True
                write_private(self.root / STATE, state)
                raw = self.compose(['exec', '-T', 'weave', '/usr/local/bin/weave', 'bootstrap', '--workspace', state['workspace'],
                                    '--username', state['username'], '--api-url', state['settings']['origin']])
                result = json.loads(raw)
                key = result.get('api_key', '')
                if result.get('workspace_id') != state['workspace'] or not isinstance(key, str) or not key.startswith('wv_sk_'):
                    raise ConfigurationError('No recoverable native operator receipt; no key was replaced.')
                state['apiKey'] = key
                write_private(self.root / STATE, state)
            script = "const fs=require('fs');const k=JSON.parse(fs.readFileSync(0,'utf8')).key;fetch('http://127.0.0.1:8080/v1/auth/me',{headers:{Authorization:'Bearer '+k}}).then(async r=>{if(!r.ok)throw Error();const v=await r.json();console.log(JSON.stringify({tenant_id:v.tenant_id,role:v.role,source:v.source}))}).catch(()=>process.exit(1))"
            subject = json.loads(self.compose(['exec', '-T', 'weave', 'node', '-e', script], json.dumps({'key': state['apiKey']})))
            if subject.get('tenant_id') != state['workspace'] or subject.get('role') != 'admin' or subject.get('source') != 'apikey':
                raise ConfigurationError('The native key did not preserve workspace and operator role.')
            state['bootstrapPending'] = False
            write_private(self.root / STATE, state)
            key_file = self.root / 'operator-key.local'
            write_private(key_file, {'apiKey': state['apiKey']})
            return {'operator': 'verified', 'privateKeyFile': key_file.name, 'adminPath': '/admin/?login=api_key', 'businessVerified': False}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('command', choices=('configure', 'bootstrap'))
    parser.add_argument('--config', default='installation.json')
    args = parser.parse_args()
    deployment = Deployment()
    print(json.dumps(deployment.configure(args.config) if args.command == 'configure' else deployment.bootstrap()))


if __name__ == '__main__':
    try:
        main()
    except (ConfigurationError, OSError, ValueError, KeyError):
        print('Standalone configuration or operation failed; private state was preserved and no credentials were logged.', file=sys.stderr)
        raise SystemExit(2) from None
